"use client";

import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";

export interface AiDraft {
  draftText: string;
  source: "LOCAL_TEMPLATE" | "EXTERNAL_LLM";
  disclaimer: string;
}

/**
 * Renders an AI-suggested draft so it is always visually distinct from the real form
 * field it's offered for (docs/roadmap/08-ai-assistance.md's core invariant: AI output
 * must never be silently blended with user-submitted content). The caller's form field
 * is only ever updated when the user explicitly clicks "Use this draft" — nothing here
 * saves anything.
 */
export function DraftSuggestionPanel({
  draft,
  onUse,
  onDiscard,
}: {
  draft: AiDraft;
  onUse: (text: string) => void;
  onDiscard: () => void;
}) {
  return (
    <div className="rounded-md border border-dashed border-accent bg-accent-soft p-3 text-sm">
      <div className="mb-2 flex items-center gap-2">
        <Badge variant="outline">AI suggestion</Badge>
        <span className="text-xs text-ink-muted">
          {draft.source === "EXTERNAL_LLM" ? "generated by an external model" : "generated locally, no external call"}
        </span>
      </div>
      <p className="whitespace-pre-wrap text-ink">{draft.draftText}</p>
      <p className="mt-2 text-xs text-ink-muted">{draft.disclaimer}</p>
      <div className="mt-3 flex gap-2">
        <Button type="button" size="sm" onClick={() => onUse(draft.draftText)}>
          Use this draft
        </Button>
        <Button type="button" size="sm" variant="secondary" onClick={onDiscard}>
          Discard
        </Button>
      </div>
    </div>
  );
}
